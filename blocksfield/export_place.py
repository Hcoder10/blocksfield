"""Export a Studio-built place to a real .rbxlx when Studio cannot be saved headless.

The world the builder made in Studio's edit mode (workspace.StudioWorld, the spawn, Lighting's sky / atmosphere /
post effects and properties, and the terrain) is serialized from the open Studio with SerializationService and
built into the final place with rojo next to the game's scripts. Terrain cannot be written by rojo, so it travels
as a TerrainRegion that a two-line server script pastes back at start.

    python -m blocksfield.export_place runs/<run> [--marker starbloom_starbloom_final]
"""
from __future__ import annotations

import argparse
import asyncio
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parent / "cybus-harness"))

EXPORT = r"""
local SS = game:GetService("SerializationService")
local HttpService = game:GetService("HttpService")
local Lighting = game:GetService("Lighting")
local function hex(buf)
	local t = table.create(buffer.len(buf))
	for i = 0, buffer.len(buf) - 1 do t[i + 1] = string.format("%02x", buffer.readu8(buf, i)) end
	return table.concat(t)
end
local out = { files = {}, lighting = {}, water = {} }
-- rojo cannot read the binary Tags property: carry tags in an attribute (StudioRestore re-applies them)
local function keepTags(root)
	for _, d in ipairs(root:GetDescendants()) do
		local tags = d:GetTags()
		if #tags > 0 then d:SetAttribute("__Tags", table.concat(tags, ",")) end
	end
	local tags = root:GetTags()
	if #tags > 0 then root:SetAttribute("__Tags", table.concat(tags, ",")) end
end
keepTags(workspace)
keepTags(Lighting)
local function put(rel, inst)
	local ok, buf = pcall(function() return SS:SerializeInstancesAsync({ inst }) end)
	if ok then out.files[rel] = hex(buf) else out.files[rel] = "ERR " .. tostring(buf) end
end
local world = workspace:FindFirstChild("StudioWorld")
if world then put("src/Workspace/StudioWorld.rbxm", world) end
for i, sp in ipairs(workspace:GetChildren()) do
	if sp:IsA("SpawnLocation") then put("src/Workspace/SpawnLocation" .. i .. ".rbxm", sp) end
end
for _, ch in ipairs(Lighting:GetChildren()) do
	put("src/Lighting/" .. ch.Name .. ".rbxm", ch)
end
local region = workspace.Terrain:CopyRegion(workspace.Terrain.MaxExtents)
region.Name = "StudioTerrain"
put("src/ServerStorage/StudioTerrain.rbxm", region)
local function c3(c) return { c.R, c.G, c.B } end
for _, p in ipairs({ "ClockTime", "Brightness", "ExposureCompensation", "EnvironmentDiffuseScale",
	"EnvironmentSpecularScale", "GeographicLatitude", "ShadowSoftness" }) do
	out.lighting[p] = Lighting[p]
end
for _, p in ipairs({ "Ambient", "OutdoorAmbient", "ColorShift_Top", "ColorShift_Bottom", "FogColor" }) do
	out.lighting[p] = c3(Lighting[p])
end
local T = workspace.Terrain
out.water = { WaterColor = c3(T.WaterColor), WaterTransparency = T.WaterTransparency,
	WaterReflectance = T.WaterReflectance, WaterWaveSize = T.WaterWaveSize, WaterWaveSpeed = T.WaterWaveSpeed }
out.min = { T.MaxExtents.Min.X, T.MaxExtents.Min.Y, T.MaxExtents.Min.Z }
return HttpService:JSONEncode(out)
"""

PASTE = """-- Restores what rojo cannot carry from the Studio-built world (generated by blocksfield.export_place):
-- the terrain (a TerrainRegion; rojo cannot write voxels) and CollectionService tags (kept in a __Tags attribute).
-- Idempotent; required first thing by World.luau so gameplay lookups see the restored world.
local done = false
return function()
\tif done then return end
\tdone = true
\tlocal region = game:GetService("ServerStorage"):FindFirstChild("StudioTerrain")
\tif region then
\t\tworkspace.Terrain:PasteRegion(region, Vector3int16.new({x}, {y}, {z}), true)
\tend
{matcolors}\tlocal CS = game:GetService("CollectionService")
\tfor _, root in ipairs({ workspace, game:GetService("Lighting") }) do
\t\tfor _, d in ipairs(root:GetDescendants()) do
\t\t\tlocal t = d:GetAttribute("__Tags")
\t\t\tif type(t) == "string" then
\t\t\t\tfor _, tag in ipairs(string.split(t, ",")) do CS:AddTag(d, tag) end
\t\t\tend
\t\tend
\tend
end
"""

HOOK = ('pcall(function() require(game:GetService("ServerScriptService"):WaitForChild("StudioRestore", 10))() end)'
        '  -- operator: restore the exported Studio world first (OPERATOR_NOTES.md)\n')


def lz4_block(src: bytes, size: int) -> bytes:
    out = bytearray()
    i = 0
    while i < len(src):
        tok = src[i]; i += 1
        lit = tok >> 4
        if lit == 15:
            while True:
                b = src[i]; i += 1; lit += b
                if b != 255: break
        out += src[i:i + lit]; i += lit
        if i >= len(src) or len(out) >= size:
            break
        off = src[i] | (src[i + 1] << 8); i += 2
        ml = tok & 15
        if ml == 15:
            while True:
                b = src[i]; i += 1; ml += b
                if b != 255: break
        ml += 4
        start = len(out) - off
        for k in range(ml):
            out.append(out[start + k])
    return bytes(out)


def strip_tags(data: bytes) -> bytes:
    """Drop the PROP chunks for Tags (newer binary type rojo rejects); everything else is copied byte for byte."""
    import struct
    import zstandard
    out = bytearray(data[:32])
    i = 32
    while i < len(data):
        name = data[i:i + 4]
        c, u, _ = struct.unpack("<III", data[i + 4:i + 16])
        body = data[i + 16:i + 16 + (c if c else u)]
        chunk = data[i:i + 16 + len(body)]
        i += 16 + len(body)
        if name == b"PROP":
            raw = body if not c else (zstandard.ZstdDecompressor().decompress(body, max_output_size=u)
                                      if body[:4] == b"\x28\xb5\x2f\xfd" else lz4_block(body, u))
            n = struct.unpack("<I", raw[4:8])[0]
            if raw[8:8 + n] == b"Tags":
                continue
        out += chunk
        if name == b"END\x00":
            break
    return bytes(out)


async def grab(marker: str) -> dict:
    from harness.tools.studio import StudioBridge
    b = StudioBridge(allow_place_ids={"0"}, place_marker=("ServerStorage.CybusHarnessRun", marker))
    await b.connect()
    try:
        r = await b.call("execution_run_luau", {"code": EXPORT, "timeout_ms": 30000})
    finally:
        await b.close()
    text = r.get("value") if isinstance(r, dict) else None
    return json.loads(text if isinstance(text, str) else json.dumps(r))


def matcolor_lines(look: str | None) -> str:
    """Terrain material colours of a LookKit look (they live on Terrain, not in the copied region)."""
    if not look:
        return ""
    import re
    src = (ROOT.parent / "cybus-harness" / "harness" / "kit" / "LookKit.luau").read_text(encoding="utf-8")
    m = re.search(r"\b" + re.escape(look) + r"\s*=\s*\{(.*?)\n\}", src, re.S)
    block = m.group(1) if m else ""
    t = re.search(r"terrain\s*=\s*\{(.*?)\}\s*,\s*\n", block, re.S)
    lines = []
    for name, r, g, b in re.findall(r"(\w+)\s*=\s*rgb\((\d+),\s*(\d+),\s*(\d+)\)", t.group(1) if t else ""):
        lines.append(f"\tpcall(function() workspace.Terrain:SetMaterialColor(Enum.Material.{name}, "
                     f"Color3.fromRGB({r}, {g}, {b})) end)\n")
    return "".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("run_dir")
    ap.add_argument("--marker", help="the run's place marker (default starbloom_<run name>)")
    ap.add_argument("--look", help="LookKit look whose terrain material colours to restore (e.g. candy)")
    a = ap.parse_args()
    run = Path(a.run_dir).resolve()
    marker = a.marker or f"starbloom_{run.name}"
    data = asyncio.run(grab(marker))
    build = run / "final_place_src"
    shutil.copytree(run / "workspace", build, ignore=shutil.ignore_patterns(".sync.json", "*.lock"),
                    dirs_exist_ok=True)
    for rel in ("src/ServerStorage/StudioBuildReplay.luau", "src/ServerScriptService/StudioBuildFallback.server.luau"):
        (build / rel).unlink(missing_ok=True)            # the real world is in the place; no runtime replay
    bad = []
    for rel, hx in data["files"].items():
        if hx.startswith("ERR"):
            bad.append(f"{rel}: {hx}")
            continue
        p = build / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(strip_tags(bytes.fromhex(hx)))
    x, y, z = (int(v) for v in data["min"])
    world_mod = build / "src/ServerScriptService/World.luau"
    if world_mod.exists() and "StudioRestore" not in world_mod.read_text(encoding="utf-8"):
        world_mod.write_text(HOOK + world_mod.read_text(encoding="utf-8"), encoding="utf-8")
    (build / "src/ServerScriptService/StudioRestore.luau").write_text(
        PASTE.replace("{x}", str(x)).replace("{y}", str(y)).replace("{z}", str(z))
        .replace("{matcolors}", matcolor_lines(a.look)), encoding="utf-8")
    proj_path = build / "default.project.json"
    proj = json.loads(proj_path.read_text(encoding="utf-8"))
    tree = proj["tree"]
    tree["Workspace"] = {"$className": "Workspace", "$path": "src/Workspace",
                         "Terrain": {"$className": "Terrain", "$properties": data["water"]}}
    old = tree.get("Lighting", {})
    props = dict(old.get("$properties") or {})
    props.update(data["lighting"])
    # the exported children (sky, atmosphere, post effects) replace the template's own
    tree["Lighting"] = {"$className": "Lighting", "$path": "src/Lighting", "$properties": props}
    proj_path.write_text(json.dumps(proj, indent=1), encoding="utf-8")
    out = run / "place" / "final.rbxlx"
    subprocess.run(["rojo", "build", str(proj_path), "-o", str(out)], check=True)
    print(f"final place: {out} ({out.stat().st_size} bytes); files: {len(data['files']) - len(bad)}")
    for b in bad:
        print("SKIPPED", b)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
